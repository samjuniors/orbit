const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('orbit', {
  getState: () => ipcRenderer.invoke('orbit:get-state'),
  discover: () => ipcRenderer.invoke('orbit:discover'),
  browseProject: () => ipcRenderer.invoke('orbit:browse-project'),
  saveSettings: payload => ipcRenderer.invoke('orbit:save-settings', payload),
  testLinear: payload => ipcRenderer.invoke('orbit:test-linear', payload),
  oauthConnect: payload => ipcRenderer.invoke('orbit:oauth-connect', payload),
  oauthDisconnect: () => ipcRenderer.invoke('orbit:oauth-disconnect'),
  oauthCancel: () => ipcRenderer.invoke('orbit:oauth-cancel'),
  connectLinearApiKey: payload => ipcRenderer.invoke('orbit:connect-linear-api-key', payload),
  fetchLinearContext: () => ipcRenderer.invoke('orbit:fetch-linear-context'),
  notionConnect: payload => ipcRenderer.invoke('orbit:notion-connect', payload),
  notionDisconnect: () => ipcRenderer.invoke('orbit:notion-disconnect'),
  notionFetchResources: () => ipcRenderer.invoke('orbit:notion-fetch-resources'),
  notionSaveSelection: payload => ipcRenderer.invoke('orbit:notion-save-selection', payload),
  obsidianListVaults: () => ipcRenderer.invoke('orbit:obsidian-list-vaults'),
  obsidianConnect: payload => ipcRenderer.invoke('orbit:obsidian-connect', payload),
  obsidianDisconnect: () => ipcRenderer.invoke('orbit:obsidian-disconnect'),
  githubConnect: payload => ipcRenderer.invoke('orbit:github-connect', payload),
  githubDisconnect: () => ipcRenderer.invoke('orbit:github-disconnect'),
  githubFetchRepos: () => ipcRenderer.invoke('orbit:github-fetch-repos'),
  githubSaveSelection: payload => ipcRenderer.invoke('orbit:github-save-selection', payload),
  approveTask: issueId => ipcRenderer.invoke('orbit:approve-task', issueId),
  rejectTask: issueId => ipcRenderer.invoke('orbit:reject-task', issueId),
  resumeTask: (issueId, note) => ipcRenderer.invoke('orbit:resume-task', { issueId, note }),
  start: () => ipcRenderer.invoke('orbit:start'),
  stop: () => ipcRenderer.invoke('orbit:stop'),
  pause: value => ipcRenderer.invoke('orbit:pause', value),
  setStartup: value => ipcRenderer.invoke('orbit:set-startup', value),
  openPath: value => ipcRenderer.invoke('orbit:open-path', value),
  openUrl: value => ipcRenderer.invoke('orbit:open-url', value),
  hideWindow: () => ipcRenderer.invoke('orbit:hide-window'),
  completeOnboarding: payload => ipcRenderer.invoke('orbit:complete-onboarding', payload),
  onEvent: callback => ipcRenderer.on('orbit:event', (_event, data) => callback(data)),
  onNavigate: callback => ipcRenderer.on('orbit:navigate', (_event, targetView) => callback(targetView))
});
